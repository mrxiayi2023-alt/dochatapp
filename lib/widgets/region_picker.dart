/// Holds a 4-level region selection result
class RegionSelection {
  final String province;
  final String? city;
  final String? district;
  final String? town;

  const RegionSelection({
    required this.province,
    this.city,
    this.district,
    this.town,
  });

  /// Full path like "福建省·三明市·三元区·城关街道"
  String get displayPath {
    return [province, city, district, town]
        .where((e) => e != null && e.isNotEmpty)
        .join('·');
  }

  /// Short path usable as a filter summary (province + city)
  String get shortPath {
    return [province, city].where((e) => e != null && e.isNotEmpty).join('·');
  }

  RegionSelection copyWithLevel(int level, String value) {
    switch (level) {
      case 1:
        return RegionSelection(province: value);
      case 2:
        return RegionSelection(province: province, city: value);
      case 3:
        return RegionSelection(province: province, city: city, district: value);
      case 4:
        return RegionSelection(province: province, city: city, district: district, town: value);
      default:
        return this;
    }
  }

  /// Match a listing against this selection (province is required, deeper levels optional)
  bool matches(
    String listingProvince,
    String listingCity, [
    String? listingArea,
    String? listingTown,
  ]) {
    if (listingProvince != province) return false;
    if (city != null && listingCity != city) return false;
    if (district != null && listingArea != null && listingArea != district) return false;
    if (town != null && listingTown != null && listingTown != town) return false;
    return true;
  }

  @override
  String toString() => displayPath;
}

