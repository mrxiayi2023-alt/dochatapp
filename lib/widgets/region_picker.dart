/// Generate realistic town/street names based on the district name
List<String> _generateTowns(String district) {
  if (district.endsWith('县') || district.endsWith('市')) {
    // Counties and county-level cities → mix of towns
    final base = district.replaceAll(RegExp(r'[市县]$'), '');
    return [
      '$base城关镇',
      '$base中心镇',
      if (base.length <= 2) '龙山镇' else '$base新城',
      '开发区',
      '工业园',
    ];
  }
  if (district == '城区') {
    return ['城区街道', '中心街道', '城关街道', '新城街道', '开发区'];
  }
  if (district.endsWith('区')) {
    // Municipal / prefectural districts → streets
    return ['城关街道', '中心街道', '新华街道', '朝阳街道', '建设街道'];
  }
  // Generic fallback
  return ['城关街道', '中心街道', '滨河街道', '新城街道', '开发区'];
}

// ────────────────── Picker implementation ──────────────────

class RegionPicker {
  RegionPicker._();

  /// Show the region picker and return the selected region.
  /// [initial] — pre-selected region (starts at the deepest available level).
  /// [maxDepth] — 4 = full (省→市→区/县→镇/街道).
  static Future<RegionSelection?> show(
    BuildContext context, {
    RegionSelection? initial,
    int maxDepth = 4,
  }) {
    return _pickLevel(
      context,
      title: '选择${_levelLabels[0]}',
      options: _provinces,
      current: initial ?? const RegionSelection(province: ''),
      level: 1,
      maxDepth: maxDepth,
    );
  }

  static Future<RegionSelection?> _pickLevel(
    BuildContext context, {
    required String title,
    required List<String> options,
    required RegionSelection current,
    required int level,
    required int maxDepth,
  }) async {
    final selected = await showCupertinoModalPopup<String>(
      context: context,
      builder: (ctx) => CupertinoActionSheet(
        title: Text(title),
        message: level < maxDepth
            ? const Text('选择后自动进入下一级', style: TextStyle(fontSize: 12, color: CupertinoColors.systemGrey))
            : null,
        actions: [
          ...options.map((o) {
            final isSelected = _valueAtLevel(current, level) == o;
            return CupertinoActionSheetAction(
              onPressed: () => Navigator.of(ctx).pop(o),
              child: Text(
                o,
                style: TextStyle(
                  fontWeight: isSelected ? FontWeight.w700 : FontWeight.w400,
                  color: isSelected ? CupertinoColors.activeBlue : CupertinoColors.black,
                ),
              ),
            );
          }),
          // Bottom row: 返回上级 (left) + 取消 (right)
          if (level > 1)
            CupertinoActionSheetAction(
              onPressed: () {},
              child: SizedBox(
                height: 44,
                child: Row(
                  children: [
                    Expanded(
                      child: GestureDetector(
                        behavior: HitTestBehavior.opaque,
                        onTap: () => Navigator.of(ctx).pop('__BACK__'),
                        child: const Center(
                          child: Text('返回上级', style: TextStyle(fontWeight: FontWeight.w600, color: CupertinoColors.activeBlue, fontSize: 20)),
                        ),
                      ),
                    ),
                    Container(width: 0.5, color: CupertinoColors.separator),
                    Expanded(
                      child: GestureDetector(
                        behavior: HitTestBehavior.opaque,
                        onTap: () => Navigator.of(ctx).pop('__CANCEL__'),
                        child: const Center(
                          child: Text('取消', style: TextStyle(fontWeight: FontWeight.w600, color: CupertinoColors.destructiveRed, fontSize: 20)),
                        ),
                      ),
                    ),
                  ],
                ),
              ),
            ),
        ],
        cancelButton: level == 1
            ? CupertinoActionSheetAction(
                onPressed: () => Navigator.of(ctx).pop('__CANCEL__'),
                child: const Text('取消', style: TextStyle(color: CupertinoColors.destructiveRed)),
              )
            : null,
      ),
    );

    // Full cancel
    if (selected == null || selected == '__CANCEL__') return null;

    // Go back one level
    if (selected == '__BACK__') return current;

    // "不限" stops the cascade at this level
    if (selected == '不限') return current;

    final updated = current.copyWithLevel(level, selected);

    // Check if there are options for the next level
    if (level < maxDepth) {
      final nextOptions = _optionsForLevel(level + 1, updated);
      if (nextOptions.isNotEmpty && context.mounted) {
        // ignore: use_build_context_synchronously
        return _pickLevel(
          context,
          title: '选择${_levelLabels[level]} — $selected',
          options: nextOptions,
          current: updated,
          level: level + 1,
          maxDepth: maxDepth,
        );
      }
    }

    return updated;
  }

  static String? _valueAtLevel(RegionSelection r, int level) {
    switch (level) {
      case 1: return r.province.isNotEmpty ? r.province : null;
      case 2: return r.city;
      case 3: return r.district;
      case 4: return r.town;
      default: return null;
    }
  }

  static List<String> _optionsForLevel(int level, RegionSelection current) {
    switch (level) {
      case 1:
        return _provinces;
      case 2:
        final cities = _cities[current.province] ?? ['其他'];
        return [...cities, '不限'];
      case 3:
        final key = '${current.province}|${current.city}';
        final districts = _districts[key] ?? _fallbackDistricts;
        return [...districts, if (!districts.contains('不限')) '不限'];
      case 4:
        return _townsFor(current.province, current.city!, current.district!);
      default:
        return [];
    }
  }
}

